def build_conv_autoencoder():

    input_layer = keras.Input(
        shape=(28, 28, 1)
    )

    # --------------------
    # Encoder
    # --------------------

    x = layers.Conv2D(
        32,
        3,
        activation="relu",
        padding="same"
    )(input_layer)

    x = layers.MaxPooling2D(
        2,
        padding="same"
    )(x)

    x = layers.Conv2D(
        64,
        3,
        activation="relu",
        padding="same"
    )(x)

    x = layers.MaxPooling2D(
        2,
        padding="same"
    )(x)

    x = layers.Conv2D(
        64,
        3,
        activation="relu",
        padding="same"
    )(x)

    # Latent feature map
    latent = x

    # --------------------
    # Decoder
    # --------------------

    x = layers.UpSampling2D(2)(latent)

    x = layers.Conv2D(
        32,
        3,
        activation="relu",
        padding="same"
    )(x)

    x = layers.UpSampling2D(2)(x)

    output = layers.Conv2D(
        1,
        3,
        activation="sigmoid",
        padding="same"
    )(x)

    autoencoder = Model(
        input_layer,
        output,
        name="Convolutional_Autoencoder"
    )

    encoder = Model(
        input_layer,
        latent,
        name="Conv_Encoder"
    )

    return autoencoder, encoder



