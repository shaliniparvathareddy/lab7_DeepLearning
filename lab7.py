def build_fc_autoencoder(latent_dim=16):

    # Input
    input_layer = keras.Input(shape=(784,))

    # Encoder
    x = layers.Dense(128, activation="relu")(input_layer)
    x = layers.Dense(32, activation="relu")(x)

    # Latent representation
    latent = layers.Dense(
        latent_dim,
        activation="relu",
        name="latent"
    )(x)

    # Decoder
    x = layers.Dense(32, activation="relu")(latent)
    x = layers.Dense(128, activation="relu")(x)

    output = layers.Dense(
        784,
        activation="sigmoid"
    )(x)

    autoencoder = Model(
        input_layer,
        output,
        name="Fully_Connected_Autoencoder"
    )

    encoder = Model(
        input_layer,
        latent,
        name="FC_Encoder"
    )

    return autoencoder, encoder



