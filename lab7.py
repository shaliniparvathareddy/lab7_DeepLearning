def build_vae_decoder(latent_dim=2):

    latent_inputs = keras.Input(
        shape=(latent_dim,),
        name="z_sampling"
    )

    x = layers.Dense(
        7 * 7 * 64,
        activation="relu"
    )(latent_inputs)

    x = layers.Reshape(
        (7, 7, 64)
    )(x)

    x = layers.Conv2DTranspose(
        64,
        3,
        strides=2,
        padding="same",
        activation="relu"
    )(x)

    x = layers.Conv2DTranspose(
        32,
        3,
        strides=2,
        padding="same",
        activation="relu"
    )(x)

    decoder_outputs = layers.Conv2DTranspose(
        1,
        3,
        padding="same",
        activation="sigmoid"
    )(x)

    decoder = Model(
        latent_inputs,
        decoder_outputs,
        name="VAE_Decoder"
    )

    return decoder

