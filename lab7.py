def build_conv_latent_autoencoder(latent_dim):

    input_layer = keras.Input(
        shape=(28, 28, 1)
    )

    # Encoder
    x = layers.Conv2D(
        32,
        3,
        activation="relu",
        padding="same"
    )(input_layer)

    x = layers.MaxPooling2D(
        2,
        padding="same"
    )(x)

    x = layers.Conv2D(
        64,
        3,
        activation="relu",
        padding="same"
    )(x)

    x = layers.MaxPooling2D(
        2,
        padding="same"
    )(x)

    x = layers.Flatten()(x)

    latent = layers.Dense(
        latent_dim,
        activation="relu",
        name="latent"
    )(x)

    # Decoder
    x = layers.Dense(
        7 * 7 * 64,
        activation="relu"
    )(latent)

    x = layers.Reshape(
        (7, 7, 64)
    )(x)

    x = layers.UpSampling2D(2)(x)

    x = layers.Conv2D(
        32,
        3,
        activation="relu",
        padding="same"
    )(x)

    x = layers.UpSampling2D(2)(x)

    output = layers.Conv2D(
        1,
        3,
        activation="sigmoid",
        padding="same"
    )(x)

    model = Model(
        input_layer,
        output
    )

    return model

