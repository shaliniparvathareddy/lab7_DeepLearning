def build_vae_encoder(latent_dim=2):

    encoder_inputs = keras.Input(
        shape=(28, 28, 1),
        name="encoder_input"
    )

    x = layers.Conv2D(
        32,
        3,
        strides=2,
        padding="same",
        activation="relu"
    )(encoder_inputs)

    x = layers.Conv2D(
        64,
        3,
        strides=2,
        padding="same",
        activation="relu"
    )(x)

    x = layers.Flatten()(x)

    x = layers.Dense(128, activation="relu")(x)

    z_mean = layers.Dense(
        latent_dim,
        name="z_mean"
    )(x)

    z_log_var = layers.Dense(
        latent_dim,
        name="z_log_var"
    )(x)

    z = Sampling()([
        z_mean,
        z_log_var
    ])

    encoder = Model(
        encoder_inputs,
        [z_mean, z_log_var, z],
        name="VAE_Encoder"
    )

    return encoder

